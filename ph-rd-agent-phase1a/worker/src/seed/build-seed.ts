import { createHash } from 'node:crypto';
import { parsePromptFile, PROMPT_KINDS, type PromptKind } from '../prompts/parse';

const tag = '$ph$';
const q = (s: string) => { if (s.includes(tag)) throw new Error('content contains the SQL quote tag'); return `${tag}${s}${tag}`; };

/** Builds supabase/seed.sql from the validated prompt files. Throws if any file has errors or warnings. */
export function buildSeedSql(files: Record<PromptKind, string>): string {
  const rows: string[] = []; const hashes: Record<string, string> = {};
  for (const kind of PROMPT_KINDS) {
    const content = files[kind];
    const r = parsePromptFile(content, kind);
    if (!r.ok || !r.parsed) throw new Error(`${kind}: ${r.errors.map(e => e.message).join('; ')}`);
    if (r.warnings.length) throw new Error(`${kind}: refusing to seed a file with warnings: ${r.warnings.map(w => w.code).join(', ')}`);
    hashes[kind] = createHash('sha256').update(content).digest('hex');
    rows.push(`(${q(kind)}, ${q(r.parsed.name)}, 1, ${q(content)}, ${q(JSON.stringify(r.parsed))}::jsonb, 'active', '[]'::jsonb, ${q(r.parsed.notes ?? '')}, now())`);
  }
  return `-- GENERATED by worker/scripts/gen-seed.ts from prompts/seed/*.md. Do not edit by hand; regenerate instead.
-- Seeds the validated Architect files as version 1 and ACTIVE for each kind.
insert into public.prompt_versions (kind, name, schema_version, content, parsed, status, validation_errors, notes, activated_at)
values
${rows.join(',\n')};

insert into public.evidence_labels (prompt_version_id, key, name, definition, criteria)
select pv.id, v.key, v.name, v.definition, v.criteria
from public.prompt_versions pv, jsonb_to_recordset(pv.parsed->'labels') as v(key text, name text, definition text, criteria text)
where pv.kind = 'evidence_labels' and pv.status = 'active';

insert into public.audit_log (action, detail)
values ('prompts_seeded', ${q(JSON.stringify({ sha256: hashes }))}::jsonb);
`;
}
